import { jsPDF } from "jspdf";

export function useExportPDF() {
  const exportChat = (messages, sessionTitle, subjectCode, userName = "Student", isEdited = false) => {
    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();
    const margin = 15;
    let y = margin;
    let pageNum = 1;

    // Helper: Add new page
    const addNewPage = () => {
      doc.addPage();
      pageNum++;
      y = margin;
      drawFooter();
    };

    // Helper: Draw footer
    const drawFooter = () => {
      doc.setFont("helvetica", "italic");
      doc.setFontSize(10);
      doc.setTextColor(150);
      doc.text(`Page ${pageNum} - Generated by CampusGPT`, pageWidth / 2, pageHeight - 10, { align: "center" });
    };

    // Helper: Print text with wrapping
    const printText = (text, isBold = false, isUser = false) => {
      doc.setFont("helvetica", isBold ? "bold" : "normal");
      doc.setFontSize(isUser ? 11 : 10);
      doc.setTextColor(isUser ? 0 : 40);

      const splitText = doc.splitTextToSize(text, pageWidth - margin * 2);
      
      splitText.forEach((line) => {
        if (y + 6 > pageHeight - 20) {
          addNewPage();
        }
        doc.text(line, margin, y);
        y += 6;
      });
      y += 2; // spacing after block
    };

    // Draw header on first page
    doc.setFont("helvetica", "bold");
    doc.setFontSize(22);
    doc.setTextColor(15, 23, 42); // Dark slate
    doc.text("CampusGPT", margin, y);
    
    doc.setFontSize(12);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(100);
    const editedText = isEdited ? " (Edited)" : "";
    doc.text(`Subject: ${subjectCode || "General"} | Date: ${new Date().toLocaleDateString()} | Student: ${userName}${editedText}`, margin, y + 8);
    
    y += 15;
    doc.setDrawColor(200);
    doc.line(margin, y, pageWidth - margin, y);
    y += 10;

    // Draw messages
    messages.forEach((msg, idx) => {
      if (y > pageHeight - 30) addNewPage();

      if (msg.role === "user") {
        doc.setFont("helvetica", "bold");
        doc.setTextColor(59, 130, 246); // Blue accent
        doc.text("You:", margin, y);
        y += 6;
        printText(msg.content, false, true);
      } else {
        doc.setFont("helvetica", "bold");
        doc.setTextColor(15, 23, 42);
        doc.text("CampusGPT:", margin, y);
        y += 6;
        
        // Handle 13-mark bold section headings natively in PDF
        const lines = msg.content.split('\n');
        lines.forEach(line => {
          if (line.match(/^[A-Z\s\(\)]+$/) && line.length > 5) {
            // Looks like a heading (e.g. "DEFINITION (2 marks)")
            printText(line, true);
          } else {
            printText(line);
          }
        });
      }

      // Divider between QA
      if (idx < messages.length - 1) {
        y += 4;
        doc.setDrawColor(230);
        doc.line(margin, y, pageWidth - margin, y);
        y += 8;
      }
    });

    drawFooter();

    // Trigger download
    const fileName = `CampusGPT_${subjectCode || 'Export'}_${new Date().toISOString().split('T')[0]}.pdf`;
    doc.save(fileName);
  };

  return { exportChat };
}
